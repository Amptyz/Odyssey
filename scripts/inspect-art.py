"""Inspect alpha and generate runtime sprite regions; never alters image pixels or .meta.
Optional authoring dependency: Pillow. Runtime/game development does not require Python.
"""
from PIL import Image
from pathlib import Path
import json,hashlib
root=Path(__file__).resolve().parents[1]
assets=root/'EmberDemo/assets/resources/art/living-ruins'
layout={'ruin-sprite':(4,4),'grovewarden':(4,4),'hero-parts':(3,2),'equipment':(4,3),'environment':(3,3)}
result={};report={}
for name,(cols,rows) in layout.items():
 p=assets/(name+'.png');im=Image.open(p);assert im.mode=='RGBA',name
 alpha=im.getchannel('A');mask=alpha.point(lambda a:255 if a>24 else 0);w,h=im.size
 def cuts(size,n,vertical):
  boundaries=[0]
  for i in range(1,n):
   center=size*i/n;span=int(size/n*.12)
   def score(pos):
    line=mask.crop((pos,0,pos+1,h) if vertical else (0,pos,w,pos+1))
    return sum(i*n for i,n in enumerate(line.histogram()))+abs(pos-center)*.01
   boundaries.append(min(range(round(center)-span,round(center)+span+1),key=score))
  return boundaries+[size]
 xs,ys=cuts(w,cols,True),cuts(h,rows,False);frames=[]
 for row in range(rows):
  for col in range(cols):
   cell=(xs[col],ys[row],xs[col+1],ys[row+1]);bbox=mask.crop(cell).getbbox();assert bbox,(name,row,col)
   x0=max(cell[0],cell[0]+bbox[0]-2);y0=max(cell[1],cell[1]+bbox[1]-2);x1=min(cell[2],cell[0]+bbox[2]+2);y1=min(cell[3],cell[1]+bbox[3]+2)
   frames.append({'rect':[x0,y0,x1-x0,y1-y0],'pivot':[(xs[col]+xs[col+1])/2-x0, y1-y0]})
 # Align each frame at its foot baseline; fixed physical pixel scale preserves action proportions.
 result[name]=frames
 report[name]={'size':[w,h],'frames':len(frames),'xCuts':xs,'yCuts':ys,'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'transparentPixels':alpha.histogram()[0]}
source='/** Generated by scripts/inspect-art.py from untouched RGBA assets. */\nexport interface ArtFrame {rect:[number,number,number,number];pivot:[number,number]}\nexport const ATLAS_FRAMES = '+json.dumps(result,separators=(',',':'))+' as const;\nexport type AtlasId=keyof typeof ATLAS_FRAMES;\n'
# Widen tuples so the engine can use mutable Size / Rect arguments without copying asset pixels.
source=source.replace(' as const;', ' satisfies Record<string,ArtFrame[]>;')
(root/'EmberDemo/assets/scripts/ember/content/art-manifest.ts').write_text(source)
(root/'art-source/living-ruins-v1/atlas-inspection.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
